#!/usr/bin/env bash
# Run the interface in a browser on pretend data (lib/preview_main.dart).
# Sample photos come from test/preview_assets (free photos, not in git).
set -euo pipefail
cd "$(dirname "$0")/.."
out=lib/preview/photos.g.dart
{
  echo "// Generated by tool/preview_web.sh from test/preview_assets. Not in git."
  echo "import 'dart:convert';"
  echo "import 'dart:typed_data';"
  echo "List<Uint8List> previewPhotos() => ["
  for f in test/preview_assets/*.jpg; do
    [ -e "$f" ] || continue
    printf "  base64Decode('%s'),\n" "$(base64 < "$f" | tr -d '\n')"
  done
  echo "];"
} > "$out"
exec flutter run -d web-server --web-port "${PORT:-8765}" -t lib/preview_main.dart
