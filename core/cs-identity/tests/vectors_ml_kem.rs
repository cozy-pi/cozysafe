use ml_kem::kem::Decapsulate;
use ml_kem::{
    Ciphertext, DecapsulationKey, EncapsulationKey, ExpandedKeyEncoding, KeyExport, MlKem768, Seed,
    B32,
};

type Dk = DecapsulationKey<MlKem768>;
type Ek = EncapsulationKey<MlKem768>;

fn hex(s: &str) -> Vec<u8> {
    let s: String = s.chars().filter(|c| !c.is_whitespace()).collect();
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

#[test]
fn key_gen() {
    for v in &KEYGEN {
        let mut seed = Seed::default();
        seed[..32].copy_from_slice(&hex(v.d));
        seed[32..].copy_from_slice(&hex(v.z));
        let dk = Dk::from_seed(seed);
        assert_eq!(
            dk.encapsulation_key().to_bytes().as_slice(),
            hex(v.ek),
            "tcId {}",
            v.tc
        );
        assert_eq!(
            dk.to_expanded_bytes().as_slice(),
            hex(v.dk),
            "tcId {}",
            v.tc
        );
    }
}

#[test]
fn encapsulate() {
    for v in &ENCAP {
        let ek = Ek::new(hex(v.ek).as_slice().try_into().unwrap()).expect("valid key");
        let m = B32::try_from(hex(v.m).as_slice()).unwrap();
        let (c, k) = ek.encapsulate_deterministic(&m);
        assert_eq!(c.as_slice(), hex(v.c), "tcId {}", v.tc);
        assert_eq!(k.as_slice(), hex(v.k), "tcId {}", v.tc);
    }
}

#[test]
fn decapsulate() {
    let mut modified = 0;
    for v in &DECAP {
        let dk =
            Dk::from_expanded_bytes(hex(v.dk).as_slice().try_into().unwrap()).expect("valid key");
        let c = Ciphertext::<MlKem768>::try_from(hex(v.c).as_slice()).unwrap();
        assert_eq!(dk.decapsulate(&c).as_slice(), hex(v.k), "tcId {}", v.tc);
        modified += usize::from(v.modified);
    }
    assert!(modified >= 2, "implicit rejection covered");
}

#[test]
fn encapsulation_key_check() {
    for v in &EK_CHECK {
        let ok = Ek::new(hex(v.key).as_slice().try_into().unwrap()).is_ok();
        assert_eq!(ok, v.ok, "tcId {}", v.tc);
    }
}

#[test]
fn decapsulation_key_check() {
    for v in &DK_CHECK {
        let ok = Dk::from_expanded_bytes(hex(v.key).as_slice().try_into().unwrap()).is_ok();
        assert_eq!(ok, v.ok, "tcId {}", v.tc);
    }
}

